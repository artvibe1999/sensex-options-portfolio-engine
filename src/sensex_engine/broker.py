"""Broker boundary. Implement against Kite only after contract and auth checks."""
from typing import Protocol

from .domain import Contract


class BrokerPort(Protocol):
    def instruments(self) -> list[Contract]: ...
    def quotes(self, instrument_tokens: list[int]) -> dict[int, dict[str, object]]: ...
    def positions(self) -> dict[str, object]: ...
    def orders(self) -> list[dict[str, object]]: ...
    def is_authenticated(self) -> bool: ...
